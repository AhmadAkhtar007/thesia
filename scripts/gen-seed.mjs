// Generates supabase/seed.sql from the app's data files: the labelled sample projects
// (src/data/sampleProjects.ts) and the Academy track and bootcamp catalogue the database
// uses for certificates and cohort access. Re-run after changing lessons or bootcamps.
//   node scripts/gen-seed.mjs

import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const tmp = path.join(os.tmpdir(), `thesia-seed-${Date.now()}.mjs`);
await esbuild.build({
  stdin: {
    contents: `export { SAMPLE_PROJECTS } from './src/data/sampleProjects.ts';
export { TRACKS } from './src/data/academy/index.ts';
export { BOOTCAMPS } from './src/data/bootcamps.ts';`,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: tmp,
  logLevel: 'warning',
});
const { SAMPLE_PROJECTS, TRACKS, BOOTCAMPS } = await import(tmp);
fs.rmSync(tmp);

const q = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const js = (o) => `${q(JSON.stringify(o))}::jsonb`;

const rows = SAMPLE_PROJECTS.map(
  (p) => `(${[
    q(p.id),
    q(p.title),
    q(p.summary),
    q(p.description),
    arr(p.fields),
    arr(p.tags),
    arr(p.levels),
    q(p.city),
    q(p.country),
    q(p.mode),
    p.hoursPerWeek,
    p.durationWeeks,
    q(p.compensation),
    q(p.stipend),
    js(p.roles),
    js(p.lead),
    q(p.ethics),
    q(p.credit),
    q(p.applyBy),
    q(p.startDate),
    q(p.status),
    'true',
    q(p.createdAt),
  ].join(', ')})`
);

const sql = `-- Sample projects for the beta (is_sample = true). Generated by scripts/gen-seed.mjs.
insert into public.projects (id, title, summary, description, fields, tags, levels, city, country, mode, hours_per_week, duration_weeks, compensation, stipend, roles, lead, ethics, credit, apply_by, start_date, status, is_sample, created_at)
values
${rows.join(',\n')}
on conflict (id) do nothing;

-- Academy tracks and bootcamps, used for certificates and free-cohort access.
insert into public.track_catalog (id, title, lesson_ids)
values
${TRACKS.map((t) => `(${q(t.id)}, ${q(t.title)}, ${arr(t.lessons.map((l) => l.id))})`).join(',\n')}
on conflict (id) do update set title = excluded.title, lesson_ids = excluded.lesson_ids;

insert into public.bootcamp_catalog (id, title, price_usd, weeks, start_date)
values
${BOOTCAMPS.map((b) => `(${q(b.id)}, ${q(b.title)}, ${b.priceUsd}, ${b.weeks}, ${q(b.start)})`).join(',\n')}
on conflict (id) do update set title = excluded.title, price_usd = excluded.price_usd, weeks = excluded.weeks, start_date = excluded.start_date;
`;
fs.writeFileSync(path.join(root, 'supabase/seed.sql'), sql);
console.log(`Wrote supabase/seed.sql: ${rows.length} sample projects, ${TRACKS.length} tracks, ${BOOTCAMPS.length} bootcamps`);
